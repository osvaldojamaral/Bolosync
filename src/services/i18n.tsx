type TranslationKey = keyof typeof translations.en;

const LanguageContext = createContext<SupportedLanguage>("hi");

export const translate = (language: string, key: TranslationKey) => {
  const selected = language === "pa" || language === "en" ? language : "hi";
  return translations[selected][key];
};

export const LanguageProvider: React.FC<{
  language: string;
  children: React.ReactNode;
}> = ({ language, children }) => (
  <LanguageContext.Provider value={language === "pa" || language === "en" ? language : "hi"}>
    {children}
  </LanguageContext.Provider>
);

export const useLanguage = () => {
  const language = useContext(LanguageContext);
  return {
    language,
    t: (key: TranslationKey) => translate(language, key),
  };
};

export type { SupportedLanguage, TranslationKey };
